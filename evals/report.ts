/** pnpm eval:report: renders evals/REPORT.md and evals/history.json from every saved run. */
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { loadDatasets } from "./datasets";
import { buildHistory, EVALS_DIR, HISTORY_FILE, readNotes, readSavedRuns, serializeHistory } from "./history";

const DIR = EVALS_DIR;

const pct = (rate?: { passRate: number; passed: number; total: number }) =>
  rate ? `${Math.round(rate.passRate * 100)}% (${rate.passed}/${rate.total})` : "–";

const saved = readSavedRuns();
const runs = [...saved].sort((a, b) => b.startedAt.localeCompare(a.startedAt));

const rows = runs.map((run) => {
  const { summary: s } = run;
  const scope = run.filters.case ? "subset" : run.filters.suite ? run.filters.suite.join("+") : "all";
  return [
    run.startedAt.slice(0, 16).replace("T", " "),
    run.label ?? "",
    `${run.git.commit}${run.git.dirty ? "*" : ""}`,
    `c ${run.promptVersions.classifier} / a ${run.promptVersions.answer}`,
    `${run.models.classifier ?? "?"} / ${run.models.answer ?? "?"}`,
    `${scope} ×${run.filters.repeat}`,
    pct(s.overall),
    pct(s.suites.routing),
    pct(s.suites.security),
    pct(s.suites.scope),
    `${s.medianTotalMs} ms`,
  ];
});

const header = ["Run", "Label", "Commit", "Prompts", "Models", "Cases", "Overall", "Routing", "Security", "Scope", "Median latency"];
const table = [header, header.map(() => "---"), ...rows].map((r) => `| ${r.join(" | ")} |`).join("\n");

const latest = runs[0];
const failures = latest?.summary.failures.length
  ? latest.summary.failures.map((f) => `- \`${f.id}\` (${f.suite}, attempt ${f.attempt}): ${f.failed.join(", ")}`).join("\n")
  : "None.";

writeFileSync(
  join(DIR, "REPORT.md"),
  `# Eval report

Generated by \`pnpm eval:report\` from \`evals/results/\`. \`*\` after a commit = uncommitted changes at run time.

${table}

## Failures in the latest run

${failures}
`,
);
console.log(`Wrote evals/REPORT.md (${runs.length} runs)`);

const history = buildHistory(saved, loadDatasets(), readNotes());
writeFileSync(HISTORY_FILE, serializeHistory(history));
console.log(`Wrote evals/history.json (${history.runs.length} full runs)`);
